export default function ToolIcon({
  href,
  fallback,
  className = "h-4 w-4",
}: {
  href: string;
  /** The tool's emoji, shown only when this route has no line icon yet. */
  fallback?: string;
  className?: string;
}) {
  const paths = PATHS[href];
  if (!paths) return fallback ? <span aria-hidden="true">{fallback}</span> : null;
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={className}
    >
      {paths}
    </svg>
  );
}
